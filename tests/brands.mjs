import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

await build({entryPoints:['lib/domain.ts','lib/brands.ts','components/brand-field.tsx','components/closet-cards.tsx'],outdir:'.test-runtime/brands-build',outExtension:{'.js':'.cjs'},bundle:true,platform:'node',format:'cjs',external:['react','react-dom','react/jsx-runtime'],logLevel:'error'});
const require=createRequire(import.meta.url),root=process.cwd()+'/.test-runtime/brands-build/';
const {itemSchema,CATEGORIES,makeSnapshot}=require(root+'lib/domain.cjs');
const {itemBrands,canonicalBrand}=require(root+'lib/brands.cjs');
const {BrandField}=require(root+'components/brand-field.cjs');
const {ItemCard}=require(root+'components/closet-cards.cjs');
const base={name:'Sample item',category:'top',color:'',seasons:[],occasions:[],notes:'',asset:null,archived:false};
assert.equal(itemSchema.parse(base).brand,undefined);
for(const category of Object.keys(CATEGORIES))assert.equal(itemSchema.parse({...base,category,brand:'  Sample brand  '}).brand,'Sample brand');
assert.equal(itemSchema.parse({...base,brand:'   '}).brand,'');
assert.throws(()=>itemSchema.parse({...base,brand:'x'.repeat(101)}),/品牌/);
const record=(brand,archived=false)=>({id:crypto.randomUUID(),kind:'item',version:1,createdAt:new Date().toISOString(),updatedAt:new Date().toISOString(),data:itemSchema.parse({...base,brand,archived})});
const records=[record('Nike'),record('nike'),record('Ｎｉｋｅ'),record('  '),record(undefined),record('优衣库',true)];
assert.deepEqual(new Set(itemBrands(records)),new Set(['Nike','优衣库']));
assert.deepEqual(itemBrands([record('Other wardrobe')]),['Other wardrobe']);
assert.equal(canonicalBrand('  NIKE ',itemBrands(records)),'Nike');
assert.equal(canonicalBrand(' New brand ',itemBrands(records)),'New brand');
assert.equal(canonicalBrand('',itemBrands(records)),'');
const snapshot=makeSnapshot({name:'Look',itemIds:[records[0].id],asset:null,occasions:[],notes:'',archived:false},records);
records[0].data.brand='Changed';assert.equal(snapshot.items[0].data.brand,'Nike');
const cover=renderToStaticMarkup(React.createElement(ItemCard,{item:records[0],onOpen:()=>{}}));assert.doesNotMatch(cover,/Changed/);
const selected=renderToStaticMarkup(React.createElement(ItemCard,{item:records[0],onOpen:()=>{},selection:{selected:false,label:'Choose item'}}));assert.doesNotMatch(selected,/Changed/);
const field=renderToStaticMarkup(React.createElement(BrandField,{value:'',brands:itemBrands(records),onChange:()=>{}}));assert.match(field,/role="combobox"/);assert.match(field,/品牌/);assert.doesNotMatch(field,/required/);
console.log('PASS: optional brands across all item categories, legacy compatibility, trimmed/case-normalized suggestions including archived items, wardrobe isolation, immutable snapshots and no brand on item cards.');
