import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
await build({entryPoints:['lib/item-filter.ts','lib/colors.ts','lib/subsets.ts'],outdir:'.test-runtime/color-filter-build',outExtension:{'.js':'.cjs'},bundle:true,platform:'node',format:'cjs',logLevel:'error'});
const require=createRequire(import.meta.url),root=process.cwd()+'/.test-runtime/color-filter-build/';
const {filterItems,wardrobeColors}=require(root+'item-filter.cjs');
const {colorKey}=require(root+'colors.cjs');
const {subsetMemberIds}=require(root+'subsets.cjs');
const navy={name:'藏蓝',hex:'#29476f'},white={name:'米白',hex:'#f0e7d1'},otherNavy={name:'藏蓝',hex:'#113355'};
const base={category:'top',archived:false,occasions:['work'],name:'Item',brand:'Brand',color:'',notes:''};
const item=(id,values,extra={})=>({id,kind:'item',data:{...base,colorStyle:{mode:values.length>1?'primary':'solid',values},...extra}});
const records=[item('top',[navy,white]),item('block',[otherNavy,white],{category:'bottom',colorStyle:{mode:'colorblock',values:[otherNavy,white]}}),item('archive',[navy],{archived:true}),item('blank',[]),{id:'legacy',kind:'item',data:{...base,color:'旧色,原文'}}];
const filters={category:'all',occasion:'all',archived:false,search:'',colors:[],members:null};
const ids=f=>filterItems(records,{...filters,...f}).map(r=>r.id);
assert.deepEqual(ids({colors:[colorKey(white)]}),['top','block']);
assert.deepEqual(ids({colors:[colorKey(navy)]}),['top']);
assert.deepEqual(ids({colors:[colorKey(navy),colorKey(otherNavy)]}),['top','block']);
assert.deepEqual(ids({colors:[colorKey(white)],category:'bottom'}),['block']);
assert.deepEqual(ids({colors:[colorKey(white)],occasion:'casual'}),[]);
assert.deepEqual(ids({colors:[colorKey(navy)],archived:true}),['archive']);
assert.deepEqual(ids({search:'米白'}),['top','block']);
assert.deepEqual(ids({search:'旧色,原文'}),['legacy']);
assert.deepEqual(ids({colors:[colorKey(white)],search:'missing'}),[]);
const groups=[{id:'parent',kind:'subset',data:{scope:'item',root:'all',parentId:null,memberIds:['top']}},{id:'child',kind:'subset',data:{scope:'item',root:'all',parentId:'parent',memberIds:['top','block']}}];
assert.deepEqual(ids({colors:[colorKey(white)],members:subsetMemberIds([...records,...groups],'parent')}),['top','block']);
assert.deepEqual(ids({colors:[colorKey(navy)],members:new Set(['block'])}),[]);
assert.equal(wardrobeColors(records).length,4);assert.deepEqual(wardrobeColors([]),[]);
assert.equal(records[0].data.colorStyle.values.length,2);
console.log('PASS: exact color identity, main/secondary/colorblock search, OR multi-selection intersected with category/occasion/archive/text/nested groups, deduplicated parent results, legacy names, uncolored items and unmodified source records.');
